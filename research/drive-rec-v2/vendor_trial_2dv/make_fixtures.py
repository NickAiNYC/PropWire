"""make_fixtures.py — SYNTHETIC harness-test fixtures for the V1-V10 verifier.

These fixtures are NOT vendor evidence. They exist to prove, before any
credits are spent, that the Decision 2D-V verifier is CORRECT and SENSITIVE:
the "clean" set must pass every automatable check, and the "faulted" set has
seven deliberately injected defects that MUST be caught by the corresponding
checks. Both variants model the documented The Odds API historical event-odds
response shape so the verifier runs byte-for-byte on dry-run output.

Every fixture directory carries SYNTHETIC.md, the fetcher records
data_label=SYNTHETIC-HARNESS-TEST in the raw manifest, and the canonical
preview carries synthetic=True — which decision_2d.quotes.validate_quotes
REFUSES (fail-closed: trial dry-run output can never feed the pilot).

Injected faults (faulted set only):
  F1 -> V2: SYN26_G07 @ T-60m snapshot timestamp 90s AFTER the decision ts
  F2 -> V3: SYN25_G01 @ T-180m one outcome with point=9999 (implausible line)
  F3 -> V4: SYN25_G02 @ T-60m book key synbook_b renamed synbook_b2
  F4 -> V5: SYN25_G03 @ T-180m price -110 with price_decimal 1.95
  F5 -> V6: SYN26_G08 synbook_c missing at T-60m and T-15m (must be ledgered)
  F6 -> V7: SYN25_G03 settlement field contradicts independent stats (says
            "over" where stats settle under); SYN26_G05 prices player
            "SYN WR Z99" who is absent from the independent stats
  F7 -> V9: SYN25_G04 @ T-15m _sim.credit_cost=25 vs modeled 10

Determinism: no RNG; all values are arithmetic functions of (game, player,
offset). Regeneration is byte-identical.
"""

from __future__ import annotations

import csv
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent

# (game_id, season, week, home, away, kickoff_utc, bin, event_id)
GAMES = [
    ("SYN25_G01", 2025, 6,  "SYN_H01", "SYN_A01", "2025-10-12T17:00:00Z", "w1-6",   "ev_syn_001"),
    ("SYN25_G02", 2025, 9,  "SYN_H02", "SYN_A02", "2025-11-02T17:00:00Z", "w7-12",  "ev_syn_002"),
    ("SYN25_G03", 2025, 14, "SYN_H03", "SYN_A03", "2025-12-07T17:00:00Z", "w13-18", "ev_syn_003"),
    ("SYN25_G04", 2025, 19, "SYN_H04", "SYN_A04", "2026-01-10T17:00:00Z", "w19-22", "ev_syn_004"),
    ("SYN26_G05", 2026, 1,  "SYN_H05", "SYN_A05", "2026-09-13T17:00:00Z", "w1-2",   "ev_syn_005"),
    ("SYN26_G06", 2026, 3,  "SYN_H06", "SYN_A06", "2026-09-27T17:00:00Z", "w3-4",   "ev_syn_006"),
    ("SYN26_G07", 2026, 5,  "SYN_H07", "SYN_A07", "2026-10-11T17:00:00Z", "w5-6",   "ev_syn_007"),
    ("SYN26_G08", 2026, 7,  "SYN_H08", "SYN_A08", "2026-10-25T17:00:00Z", "w7-7",   "ev_syn_008"),
]
OFFSETS = [("T-180m", -180), ("T-60m", -60), ("T-15m", -15)]
BOOKS = [("synbook_a", "Synthetic Book A", 30),
         ("synbook_b", "Synthetic Book B", 15),
         ("synbook_c", "Synthetic Book C", 5)]
N_PLAYERS = 8
MARKET_KEY = "player_receiving_yards"
UNMATCHED_PLAYER = "SYN WR Z99"     # priced in the faulted set, absent from stats

SYNTHETIC_MD = """# SYNTHETIC HARNESS-TEST FIXTURES — NOT VENDOR DATA

Everything in this directory is generated by make_fixtures.py to test the
Decision 2D-V verification code. No vendor request was made, no credits were
consumed, and no file here is evidence about The Odds API, SportsDataIO, or
any sportsbook. The fetcher labels dry-run output data_label=
SYNTHETIC-HARNESS-TEST and the canonical preview carries synthetic=True,
which the pilot quote store refuses by design.
"""


def players_for(gi: int) -> list[str]:
    letter = chr(ord("A") + gi)
    return [f"SYN WR {letter}{i:02d}" for i in range(1, N_PLAYERS + 1)]


def line_for(pi: int, offset_idx: int) -> float:
    base = 25 + 5 * (pi + 1)
    line = float(base) if (pi + 1) == 4 else base + 0.5   # player 4: integer line (push test)
    if pi == 0 and offset_idx >= 1:                        # player 1: line moves down pregame
        line -= 2.0
    return line


def prices_for(pi: int, offset_idx: int) -> tuple[int, int]:
    k = (pi + offset_idx) % 3
    over = -110 - 5 * (k - 1)                              # -115 / -110 / -105
    return over, -220 - over


def decimal_of(american: int) -> float:
    return round(1.0 + (100.0 / abs(american) if american < 0
                        else american / 100.0), 4)


def stats_yards(pi: int) -> int:
    """Settled yards: deltas cycle over/under/push against the FINAL line."""
    deltas = [12, -8, 3, 0, -15, 25, -2, 7]
    return int(line_for(pi, 2)) + deltas[pi]


def build_response(gi: int, offset_idx: int, faulted: bool) -> dict:
    gid, _season, _week, home, away, ko_iso, _bin, evid = GAMES[gi]
    kickoff = datetime.strptime(ko_iso, "%Y-%m-%dT%H:%M:%SZ").replace(
        tzinfo=timezone.utc)
    label = OFFSETS[offset_idx][0]
    decision_ts = kickoff + timedelta(minutes=OFFSETS[offset_idx][1])
    snap_ts = decision_ts + timedelta(seconds=90) if (
        faulted and gid == "SYN26_G07" and label == "T-60m") else \
        decision_ts - timedelta(seconds=45)

    books = []
    for key, title, lag_s in BOOKS:
        if faulted and gid == "SYN26_G08" and key == "synbook_c" \
                and offset_idx >= 1:
            continue                                       # F5: book disappears
        use_key = key
        if faulted and gid == "SYN25_G02" and key == "synbook_b" \
                and label == "T-60m":
            use_key = "synbook_b2"                         # F3: key instability
        outcomes = []
        priced = list(players_for(gi))
        if faulted and gid == "SYN26_G05":
            priced.append(UNMATCHED_PLAYER)                # F6b: not in stats
        for pi, pname in enumerate(priced):
            if pi == N_PLAYERS and offset_idx == 2:
                continue                                   # Z99 pulled at T-15m like player 8
            if pi == N_PLAYERS - 1 and offset_idx == 2:
                continue                                   # player 8 line pulled at T-15m (clean behavior)
            line = line_for(pi, offset_idx)
            if faulted and gid == "SYN25_G01" and label == "T-180m" and pi == 2:
                line = 9999.0                              # F2: implausible line
            over, under = prices_for(pi, offset_idx)
            ov = {"description": pname, "label": "Over", "price": over,
                  "point": line, "price_decimal": decimal_of(over)}
            un = {"description": pname, "label": "Under", "price": under,
                  "point": line, "price_decimal": decimal_of(under)}
            if faulted and gid == "SYN25_G03" and label == "T-180m" and pi == 4:
                ov["price_decimal"] = 1.95                 # F4: conversion mismatch
                ov["settlement"] = "over"                  # F6a: stats settle UNDER -> contradiction
            outcomes.append(ov)
            outcomes.append(un)
        books.append({
            "key": use_key, "title": title,
            "last_update": int((snap_ts - timedelta(seconds=lag_s)).timestamp()),
            "markets": [{"key": MARKET_KEY, "outcomes": outcomes}],
        })

    doc = {
        "game_id": evid,
        "sport_key": "playerprops_nfl",
        "sport_title": "NFL Player Props (SYNTHETIC)",
        "commence_time": ko_iso,
        "home_team": home,
        "away_team": away,
        "timestamp": int(snap_ts.timestamp()),
        "previous_timestamp": int((snap_ts - timedelta(minutes=5)).timestamp()),
        "next_timestamp": int((snap_ts + timedelta(minutes=5)).timestamp()),
        "bookmakers": books,
        "_synthetic_fixture": True,
    }
    if faulted and gid == "SYN25_G04" and label == "T-15m":
        doc["_sim"] = {"credit_cost": 25}                  # F7: header mismatch
    return doc


def build_stats() -> list[dict]:
    rows = []
    for gi in range(len(GAMES)):
        gid = GAMES[gi][0]
        for pi, pname in enumerate(players_for(gi)):
            rows.append({"game_id": gid, "player_name": pname,
                         "receiving_yards": stats_yards(pi)})
    return rows


def build_sample_manifest() -> dict:
    return {
        "trial_id": "DECISION_2DV_TRIAL_v1",
        "selection_rule": "SYNTHETIC harness-test sample (8 games, both seasons)",
        "seed_source": "SYNTHETIC-FIXTURES",
        "source": "make_fixtures.py — NOT schedule data",
        "counts": {"season_2025_games_available": 4,
                   "season_2026_w1_7_games_available": 4},
        "games": [
            {"game_id": g[0], "season": g[1], "week": g[2], "game_type": "REG",
             "gameday": g[5][:10], "home_team": g[3], "away_team": g[4],
             "bin": g[6], "event_id": g[7], "kickoff_utc": g[5]}
            for g in GAMES
        ],
        "fixed_at_note": "synthetic fixtures; regenerate deterministically",
    }


def write_variant(variant: str) -> None:
    faulted = variant == "faulted"
    out = HERE / "fixtures" / variant
    (out / "responses").mkdir(parents=True, exist_ok=True)
    (out / "SYNTHETIC.md").write_text(SYNTHETIC_MD)
    (out / "sample_manifest.json").write_text(
        json.dumps(build_sample_manifest(), indent=2, sort_keys=True) + "\n")
    for gi in range(len(GAMES)):
        for offset_idx in range(len(OFFSETS)):
            doc = build_response(gi, offset_idx, faulted)
            name = f"{GAMES[gi][0]}__{OFFSETS[offset_idx][0]}.json"
            (out / "responses" / name).write_text(
                json.dumps(doc, indent=2, sort_keys=True) + "\n")
    # independent stats (identical for both variants: the quote-side faults are
    # a contradicting settlement field and a player absent from these stats)
    with (out / "independent_stats.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["game_id", "player_name",
                                          "receiving_yards"])
        w.writeheader()
        for r in build_stats():
            w.writerow(r)
    n = len(list((out / "responses").glob("*.json")))
    print(f"wrote fixtures/{variant}: {n} responses + manifest + stats "
          f"(faulted={faulted})")


if __name__ == "__main__":
    write_variant("clean")
    write_variant("faulted")
